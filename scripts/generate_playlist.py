"""Generate the static playlist and cached artwork from mp3s/*.mp3."""

from __future__ import annotations

import hashlib
import json
import mimetypes
from urllib.parse import quote
from pathlib import Path

from mutagen.id3 import ID3
from mutagen.mp3 import MP3

ROOT = Path(__file__).resolve().parent.parent
AUDIO_DIR = ROOT / "mp3s"
ARTWORK_DIR = ROOT / "radio" / "assets" / "artwork"
PLAYLIST_FILE = ROOT / "radio" / "playlist.js"


def text_tag(tags: ID3, name: str, fallback: str) -> str:
    value = tags.get(name)
    return str(value[0]).strip() if value and value[0] else fallback


def main() -> None:
    ARTWORK_DIR.mkdir(parents=True, exist_ok=True)
    tracks = []
    for path in sorted(AUDIO_DIR.glob("*.mp3"), key=lambda item: item.name.lower()):
        audio = MP3(path)
        tags = audio.tags or ID3()
        track_id = hashlib.sha256(path.name.encode("utf-8")).hexdigest()[:16]
        artwork = None
        pictures = tags.getall("APIC")
        if pictures:
            picture = pictures[0]
            extension = mimetypes.guess_extension(picture.mime) or ".jpg"
            artwork_path = ARTWORK_DIR / f"{track_id}{extension}"
            artwork_path.write_bytes(picture.data)
            artwork = f"assets/artwork/{artwork_path.name}"
        tracks.append({
            "id": track_id,
            "title": text_tag(tags, "TIT2", path.stem),
            "artist": text_tag(tags, "TPE1", "Ty deBruyn Radio"),
            "duration": round(float(audio.info.length), 3),
            "url": f"../mp3s/{quote(path.name)}",
            "artwork": artwork,
        })

    output = """/*
 * Generated by scripts/generate_playlist.py. Do not edit manually.
 * Add MP3 files to mp3s/ and run the generator (or push to GitHub).
 */
window.RADIO_PLAYLIST = %s;
""" % json.dumps(tracks, ensure_ascii=False, indent=2)
    PLAYLIST_FILE.write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
